  ADD COLUMN IF NOT EXISTS area_subdistrict TEXT NOT NULL DEFAULT '';
ALTER TABLE marriage_profiles
  ADD COLUMN IF NOT EXISTS area_district    TEXT NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS area_subdistrict TEXT NOT NULL DEFAULT '';
