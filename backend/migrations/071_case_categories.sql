-- Tag column on cases. Nullable (a case may be uncategorized); free VARCHAR so
-- a category delete never breaks existing cases (they keep the slug text,
-- just drop out of the capsule filter). Indexed for the per-category filter.
ALTER TABLE beneficiary_cases
  ADD COLUMN IF NOT EXISTS category_slug VARCHAR(64);

CREATE INDEX IF NOT EXISTS idx_beneficiary_cases_category
  ON beneficiary_cases (category_slug)
  WHERE category_slug IS NOT NULL;
