-- 071 — Beneficiary case categories: Quick Filter Capsules (client spec,
-- Home screen "Section Three").
--
-- An admin-managed, ordered, 4-language taxonomy for beneficiary cases
-- (Orphan Sponsorship, Widow Support, Food Baskets, etc.). Each case can be
-- tagged with one category_slug; the app shows capsule filter chips on Home
-- that jump into the case list pre-filtered. Mirrors the media_categories
-- CMS pattern (032) exactly.
CREATE TABLE IF NOT EXISTS case_categories (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug          VARCHAR(64)  NOT NULL UNIQUE,
  name_en       VARCHAR(120) NOT NULL,
  name_ar       VARCHAR(120) NOT NULL DEFAULT '',
  name_ckb      VARCHAR(120) NOT NULL DEFAULT '',
  name_kmr      VARCHAR(120) NOT NULL DEFAULT '',
  display_order INTEGER      NOT NULL DEFAULT 0,
  active        SMALLINT     NOT NULL DEFAULT 1,
  created_by    INTEGER,
  created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

