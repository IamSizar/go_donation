-- 143_wallet_topup_requests.sql
-- R2 #67 — a user can ask for money to be added to their wallet. The request
-- records the payment method they used (from the same list donations use), the
-- amount, an optional transfer reference/note and an optional proof photo.
-- It stays 'pending' and the wallet is NOT touched until staff approve it from
-- the dashboard; approving credits the wallet and writes the ledger row in one
-- transaction. Nothing in the app can credit a wallet by itself.
CREATE TABLE IF NOT EXISTS wallet_topup_requests (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id        INTEGER      NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  amount_iqd     BIGINT       NOT NULL CHECK (amount_iqd > 0),
  payment_method VARCHAR(64)  NOT NULL DEFAULT '',
  note           TEXT         NOT NULL DEFAULT '',
  proof_path     VARCHAR(500),
  status         VARCHAR(16)  NOT NULL DEFAULT 'pending'
                 CHECK (status IN ('pending', 'approved', 'rejected')),
  reject_reason  TEXT,
  decided_by     INTEGER,
  decided_at     TIMESTAMP,
  created_at     TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_wallet_topup_requests_user   ON wallet_topup_requests(user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_wallet_topup_requests_status ON wallet_topup_requests(status, created_at DESC);
