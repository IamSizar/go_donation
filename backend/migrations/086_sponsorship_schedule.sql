-- 2. The schedule itself: one row per due date per sponsorship. Generated from
--    the sponsorship's interval, so "the system should automatically create a
--    schedule for each case" is a data operation, not manual entry.
--
--    status drives the tracking screen:
--      upcoming — due in the future
--      due      — due today / within the grace window, not yet paid
--      overdue  — past due, not paid
--      paid     — settled (history)
--      skipped  — deliberately passed over by staff (history)
CREATE TABLE IF NOT EXISTS sponsorship_schedule (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sponsorship_id  BIGINT      NOT NULL REFERENCES sponsorships(id) ON DELETE CASCADE,
  due_date        DATE        NOT NULL,
  amount          NUMERIC(14,2) NOT NULL DEFAULT 0.00,
  currency        CHAR(3)     NOT NULL DEFAULT 'IQD',
  status          VARCHAR(16) NOT NULL DEFAULT 'upcoming'
                   CHECK (status IN ('upcoming','due','overdue','paid','skipped')),
  paid_at         TIMESTAMP,
  notes           TEXT,
  -- Reminder bookkeeping so a notification is never sent twice for the same
  -- occurrence, per recipient side.
  reminded_grantor_at   TIMESTAMP,
  reminded_recipient_at TIMESTAMP,
  created_at      TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at      TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (sponsorship_id, due_date)
);

CREATE INDEX IF NOT EXISTS idx_sponsorship_schedule_sponsorship
  ON sponsorship_schedule(sponsorship_id);
CREATE INDEX IF NOT EXISTS idx_sponsorship_schedule_due
  ON sponsorship_schedule(due_date, status);

CREATE TRIGGER trg_sponsorship_schedule_updated_at
  BEFORE UPDATE ON sponsorship_schedule
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

