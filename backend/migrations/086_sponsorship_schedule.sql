-- 086 — "Eighth: Sponsorship Schedule and Calendar".
--
-- Already present, reused: sponsorships.schedule_interval
-- (weekly|monthly|quarterly|yearly) and sponsorships.next_due_date give each
-- sponsorship its recurrence rule and its next date. What was missing is the
-- schedule itself — a row per due date — which is what upcoming / due /
-- overdue / history tracking and the reminders need.

-- 1. Admin-managed assistance types ("4. Scalability": new types of assistance
--    without programming changes). sponsorships.sponsorship_type is a free
--    VARCHAR, so this is a curated picker over the same values rather than a
--    constraint — existing rows keep working untouched.
CREATE TABLE IF NOT EXISTS sponsorship_types (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug          VARCHAR(64)  NOT NULL UNIQUE,
  name_en       VARCHAR(120) NOT NULL,
  name_ar       VARCHAR(120) NOT NULL DEFAULT '',
  name_ckb      VARCHAR(120) NOT NULL DEFAULT '',
  name_kmr      VARCHAR(120) NOT NULL DEFAULT '',
  -- Default recurrence suggested when staff pick this type.
  default_interval VARCHAR(16) NOT NULL DEFAULT 'monthly'
                    CHECK (default_interval IN ('weekly','monthly','quarterly','yearly')),
  display_order INTEGER      NOT NULL DEFAULT 0,
  active        SMALLINT     NOT NULL DEFAULT 1,
  created_by    INTEGER,
  created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

